"""
Research Report Generator
Synthesizes comprehensive scientific reports in Markdown, JSON, and CSV formats.
Documents objectives, mathematical formulations, metrics, benchmarks, and limitations.
"""

from typing import Dict, Any, List
import json
import csv
import io

def generate_markdown_report(
    experiment_data: Dict[str, Any],
    benchmarks: List[Dict[str, Any]],
    image_meta: Dict[str, Any],
) -> str:
    """Generates an academic-grade research paper report in Markdown format."""
    lines = []
    lines.append("# Research Report: Perceptual Image Quality & Structural Similarity Analysis")
    lines.append(f"**Generated by SSIM LAB** | Date: `{experiment_data.get('timestamp', 'N/A')}` | ID: `{experiment_data.get('id', 'N/A')}`\n")
    lines.append("---\n")

    lines.append("## 1. Executive Objective")
    lines.append("This study evaluates the structural degradation and perceptual recovery of digital imagery under parametric physical and transmission distortions. Rather than relying on traditional Mean Squared Error (MSE), which correlates poorly with the Human Visual System (HVS), we examine localized luminance, contrast, and structural cross-correlations using the Structural Similarity (SSIM) and Multi-Scale SSIM (MS-SSIM) frameworks.\n")

    lines.append("## 2. Image Sample & Environment Metadata")
    lines.append(f"- **Sample Name:** {experiment_data.get('image_name', 'Input Image')}")
    lines.append(f"- **Spatial Dimensions:** {image_meta.get('width', 256)} × {image_meta.get('height', 256)} pixels")
    lines.append(f"- **Color Channels:** {image_meta.get('channels', 3)} (RGB)")
    lines.append(f"- **Execution Engine:** PyTorch 2.x (Unified Track A Scientific Studio)")
    lines.append(f"- **Reproducibility Seed:** `{experiment_data.get('seed', 'None')}`\n")

    lines.append("## 3. Mathematical Methodology")
    lines.append("### 3.1 Standard SSIM Formulation (Wang et al., 2004)")
    lines.append("$$\\text{SSIM}(x, y) = \\frac{(2\\mu_x\\mu_y + C_1)(2\\sigma_{xy} + C_2)}{(\\mu_x^2 + \\mu_y^2 + C_1)(\\sigma_x^2 + \\sigma_y^2 + C_2)}$$")
    lines.append("Where constants $C_1 = (0.01 \\cdot L)^2$ and $C_2 = (0.03 \\cdot L)^2$ dynamically adapt to the dynamic range $L$.\n")

    lines.append("### 3.2 Multi-Scale SSIM (Wang et al., 2003)")
    lines.append("Evaluated across $M=5$ dyadic pyramid scales using $2 \\times 2$ decimation downsampling, pooling contrast and structure with empirical weights $\\beta = [0.0448, 0.2856, 0.3001, 0.2363, 0.1333]$.\n")

    lines.append("## 4. Parametric Distortion Configuration")
    dist = experiment_data.get("distortion", {})
    lines.append(f"- **Distortion Type Applied:** `{dist.get('type', 'None')}`")
    lines.append(f"- **Parameters:** `{json.dumps(dist.get('params', {}))}`\n")

    lines.append("## 5. Multi-Algorithm Restoration Benchmarking")
    lines.append("| Algorithm | SSIM Index | MS-SSIM | PSNR (dB) | Pixel MSE | Recovery (Δ SSIM) | Runtime (ms) |")
    lines.append("|---|:---:|:---:|:---:|:---:|:---:|:---:|")

    for row in benchmarks:
        alg = row.get("algorithm", "N/A")
        s = row.get("ssim", 0.0)
        ms = row.get("ms_ssim", 0.0)
        p = row.get("psnr_db", 0.0)
        m = row.get("mse", 0.0)
        d = row.get("delta_ssim", 0.0)
        rt = row.get("runtime_ms", 0.0)
        delta_str = f"+{d:.4f}" if d > 0 else f"{d:.4f}"
        lines.append(f"| **{alg}** | {s:.4f} | {ms:.4f} | {p:.2f} | {m:.2f} | `{delta_str}` | {rt:.2f} ms |")

    lines.append("\n## 6. Analytical Conclusions & Limitations")
    lines.append("1. **Perceptual Divergence from MSE:** Non-structural degradations (e.g. mean shift) produce large MSE penalties despite near-perfect structural retention ($SSIM > 0.98$). Conversely, spatial blur and JPEG quantization destroy high-frequency edge gradients, causing severe SSIM drops.")
    lines.append("2. **Restoration Recovery:** Edge-preserving bilateral filtering and Non-Local Means (NLM) achieve positive recovery deltas ($\\Delta \\text{SSIM} > 0$) on noise contamination, while unsharp masking may introduce ringing artifacts if over-parameterized.")
    lines.append("3. **Academic Reference:** Z. Wang, A. C. Bovik, H. R. Sheikh, E. P. Simoncelli, *IEEE Transactions on Image Processing*, 2004.\n")

    return "\n".join(lines)

def generate_csv_report(benchmarks: List[Dict[str, Any]]) -> str:
    """Exports benchmark measurements to RFC 4180 CSV format."""
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["Algorithm", "SSIM", "MS-SSIM", "PSNR_dB", "MSE", "Delta_SSIM", "Runtime_ms", "Memory_KB", "Status"])
    for b in benchmarks:
        writer.writerow([
            b.get("algorithm", ""),
            b.get("ssim", ""),
            b.get("ms_ssim", ""),
            b.get("psnr_db", ""),
            b.get("mse", ""),
            b.get("delta_ssim", ""),
            b.get("runtime_ms", ""),
            b.get("memory_kb", ""),
            b.get("status", ""),
        ])
    return output.getvalue()
